import torch
import open_clip
from PIL import Image

# 1. Load BioCLIP-2
print("Loading BioCLIP-2...")

model, _, preprocess = open_clip.create_model_and_transforms(
    "hf-hub:imageomics/bioclip-2"
)

tokenizer = open_clip.get_tokenizer(
    "hf-hub:imageomics/bioclip-2"
)

model.eval()

# 2. Enter your image path
image_path = input("Enter image path: ").strip().strip('"')

try:
    image = Image.open(image_path).convert("RGB")
except Exception as e:
    print("Could not open image:", e)
    raise SystemExit(1)

image_tensor = preprocess(image).unsqueeze(0)

# 3. Candidate species to test
labels = [
    "Yellow Trout Lily (Erythronium americanum)",
    "White Trout Lily (Erythronium albidum)",
    "Sunflower (Helianthus annuus)",
    "Rose (Rosa species)",
    "Tulip (Tulipa species)",
    "Daffodil (Narcissus species)",
    "Lotus (Nelumbo nucifera)",
    "White Daisy (Leucanthemum vulgare)",
    "Orchid (Orchidaceae)",
    "Unknown plant species"
]

# 4. Compare image and text
print("\nAnalyzing image...")

with torch.inference_mode():
    image_features = model.encode_image(image_tensor)
    text_tokens = tokenizer(
        [f"a photograph of {label}" for label in labels]
    )
    text_features = model.encode_text(text_tokens)

    image_features = image_features / image_features.norm(
        dim=-1, keepdim=True
    )
    text_features = text_features / text_features.norm(
        dim=-1, keepdim=True
    )

    similarities = (image_features @ text_features.T).squeeze(0)

# 5. Display top 5 matches
top_indices = similarities.argsort(descending=True)[:5]

print("\nTop 5 predictions:")
for rank, idx in enumerate(top_indices, start=1):
    i = idx.item()
    print(f"{rank}. {labels[i]} — similarity: {similarities[i].item():.4f}")
